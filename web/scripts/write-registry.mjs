import { readdir, writeFile, access } from "node:fs/promises";

/**
 * Generate the two files that name every instrument.
 *
 * Both are lists of literal imports rather than a glob, and that is the point:
 * the bundler can only split code it can see, so a computed specifier would
 * mean shipping all sixteen instruments to whoever opened one. Generating them
 * keeps the literals honest — a folder that exists but is missing from the
 * manifest is a silent absence, and hand-maintaining sixteen entries in two
 * files is exactly where that happens.
 *
 * Catalogue order is the order here, so it is declared rather than alphabetical.
 */
const ORDER = [
  "love-languages", "attachment", "couple-conversations", "intimacy-conditions",
  "attraction", "intimacy-map", "conflict-style", "enneagram", "big-five",
  "hexaco", "jungian", "riasec", "working-style", "study-practice",
  "chronotype", "numerology",
];

const dirs = (await readdir("src/instruments", { withFileTypes: true }))
  .filter((d) => d.isDirectory())
  .map((d) => d.name);

const ready = [];
for (const id of ORDER) {
  if (!dirs.includes(id)) continue;
  try {
    // `index.ts` is the entry point both generated files import, so it — not
    // `spec.ts` — is what "ported" means. Keying off the spec listed folders
    // whose module wrapper had not been written yet, and produced a manifest
    // that did not compile.
    await access(`src/instruments/${id}/index.ts`);
    ready.push(id);
  } catch {
    /* not ported yet */
  }
}
const skipped = dirs.filter((d) => !ready.includes(d));

const camel = (id) => id.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

await writeFile(
  "src/instruments/index.ts",
  `/**
 * Every instrument, in catalogue order.
 *
 * Generated by scripts/write-registry.mjs. Static imports rather than a glob:
 * the list is the manifest, a missing entry shows up as a diff, and the
 * bundler can see the whole graph. Message tables stay lazy — they are the
 * large part — so adding a locale costs nothing at the entry point.
 */
import { createRegistry, type InstrumentModule } from "@/core/registry";

${ready.map((id) => `import ${camel(id)} from "./${id}";`).join("\n")}

const MODULES = [
${ready.map((id) => `  ${camel(id)},`).join("\n")}
] as unknown as InstrumentModule[];

export const registry = createRegistry(MODULES);
export default registry;
`,
  "utf8",
);

await writeFile(
  "src/instruments/lazy.ts",
  `/**
 * One dynamic import per instrument, written out as literals.
 *
 * Generated by scripts/write-registry.mjs.
 *
 * The runner and the result page both need an instrument's own code — score()
 * to compute a reading, View to draw it — and both are client routes, because
 * a result lives in local storage and never reaches a server. Importing the
 * registry there would put every instrument in the bundle of whichever one the
 * reader opened. A map of literal import() calls is what lets the bundler
 * split them; a computed specifier resolves at runtime but leaves the graph
 * unknowable, so the bundler either ships everything or nothing.
 */
import type { InstrumentModule } from "@/core/registry";

type Loader = () => Promise<{ default: InstrumentModule }>;

const LOADERS: Record<string, Loader> = {
${ready.map((id) => `  "${id}": () => import("./${id}") as Promise<{ default: InstrumentModule }>,`).join("\n")}
};

export const hasInstrument = (id: string) => id in LOADERS;

export async function loadInstrumentModule(id: string): Promise<InstrumentModule | null> {
  const loader = LOADERS[id];
  if (!loader) return null;
  return (await loader()).default;
}
`,
  "utf8",
);

console.log(`registered ${ready.length}: ${ready.join(", ")}`);
if (skipped.length) console.log(`SKIPPED (no index.ts): ${skipped.join(", ")}`);
